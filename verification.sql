 ASSERT (SELECT COUNT(*) FROM subquery_copy)=3, 'Q30: persistent table with subquery';
 ASSERT (SELECT COUNT(*) FROM (SELECT 1 UNION ALL SELECT 1)t)=2 AND (SELECT COUNT(*) FROM (SELECT 1 UNION SELECT 1)t)=1, 'Q9';
 ASSERT (SELECT COUNT(*) FROM sample WHERE id IN (VALUES(1),(2)))=2, 'Q3: VALUES in WHERE subquery';
 ASSERT (SELECT COUNT(*) FROM (VALUES(1),(2))t)=2, 'Q3: VALUES in FROM';
 ASSERT (WITH RECURSIVE r(n) AS (VALUES(1) UNION ALL SELECT n+1 FROM r WHERE n<3) SELECT MAX(n) FROM r)=3, 'Q3/Q38: recursive VALUES and termination';
 ASSERT (SELECT MAX(r) FROM (SELECT RANK() OVER() r FROM sample)t)=1, 'Q63/Q84: ranking without ORDER BY';
 ASSERT (SELECT COUNT(DISTINCT r) FROM (SELECT ROW_NUMBER() OVER() r FROM sample)t)=3, 'Q63: ROW_NUMBER unique per partition';
