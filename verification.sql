 ASSERT ROUND(1691.7,-1)=1690, 'Q32: tens';
 ASSERT ROUND(1.6)=2 AND TRUNC(1.6)=1 AND FLOOR(1.6)=1 AND CEIL(1.6)=2, 'Q29/Q96: distinct rounding modes';
 ASSERT ROUND(1.6,1)=1.6, 'Q29: no nearest-integer option';
 ASSERT SUBSTRING('hello world' FROM 7)='world' AND SUBSTRING('hello world' FROM 1 FOR 5)='hello', 'Q54';
 ASSERT SUBSTRING('hello world' FROM 1)='hello world' AND SUBSTRING('hello world' FROM -5)='hello world', 'Q54 rejected options';
 ASSERT CONCAT('a','b')='ab' AND LENGTH('abc')=3 AND LOWER('ABC')='abc', 'Q69';
 ASSERT REPLACE('abc','b','x')='axc' AND TRIM(' x ')='x' AND SUBSTRING('abc' FROM 2)='bc', 'Q102';
 ASSERT TO_DATE('2026-11-13','YYYY-MM-DD')=DATE '2026-11-13', 'Q72/Q99';
 ASSERT EXTRACT(year FROM DATE '2026-11-13')=2026, 'Q99';
 ASSERT AGE(DATE '2026-11-13', DATE '2025-11-13')=INTERVAL '1 year', 'Q99';
 ASSERT pg_typeof(CURRENT_DATE)::text='date' AND pg_typeof(CURRENT_TIME)::text='time with time zone', 'Q8';
 ASSERT CURRENT_TIMESTAMP=NOW(), 'Q74';
 ASSERT '123'::integer=123 AND CAST('123' AS integer)=123, 'Q107';
 ASSERT CAST(123 AS text)='123' AND CAST('2026-11-13' AS date)=DATE '2026-11-13', 'Q111';
