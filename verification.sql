BEGIN;
CREATE SCHEMA bdtest2_audit;
SET LOCAL search_path = bdtest2_audit, public;
CREATE EXTENSION IF NOT EXISTS tablefunc;
CREATE TABLE sample (id integer PRIMARY KEY, value integer NOT NULL);
INSERT INTO sample VALUES (1,10),(2,20),(3,20);
CREATE TABLE cast_copy AS SELECT CAST(id AS text) AS id FROM sample;
CREATE TABLE subquery_copy AS SELECT * FROM sample WHERE id IN (SELECT id FROM sample);
CREATE VIEW simple_view AS SELECT id,value FROM sample;
CREATE VIEW computed_view AS SELECT id,value,value*2 AS doubled FROM sample;
CREATE VIEW checked_view AS SELECT * FROM sample WHERE value>0 WITH CHECK OPTION;
CREATE MATERIALIZED VIEW cached AS SELECT SUM(value) AS total FROM sample;
CREATE FUNCTION returns_nothing() RETURNS void LANGUAGE sql AS 'SELECT NULL::void';
CREATE FUNCTION modifies_data() RETURNS void LANGUAGE sql AS 'UPDATE sample SET value=value WHERE id=1';
CREATE TABLE parent(id integer PRIMARY KEY);
CREATE TABLE child(parent_id integer REFERENCES parent(id));
INSERT INTO child VALUES (NULL);
CREATE TABLE truncate_sample(id integer);
INSERT INTO truncate_sample VALUES(1);
SAVEPOINT before_truncate;
TRUNCATE truncate_sample;
ROLLBACK TO before_truncate;
DO $$
DECLARE actual numeric; result_count integer;
BEGIN
